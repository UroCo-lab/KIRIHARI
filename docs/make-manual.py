def t(x,y,s,size=11.5,bold=False,color=INK):
    c.setFillColor(color); c.setFont('JPB' if bold else 'JP',size); c.drawString(x,y,s)

def wrap(s,width,size=11.5,bold=False):
    font='JPB' if bold else 'JP'; rows=[]; line=''
    for ch in s:
        if ch=='\n': rows.append(line); line=''; continue
        if pdfmetrics.stringWidth(line+ch,font,size)>width and line:
            rows.append(line); line=ch
        else: line+=ch
    if line: rows.append(line)
    return rows

def p(s,y,x=35,width=525,size=11.5,bold=False,color=INK,leading=18):
    for line in wrap(s,width,size,bold): t(x,y,line,size,bold,color); y-=leading
    return y

def section(label,y):
    t(35,y,label,15,True,TEAL)
    c.setStrokeColor(LINE); c.setLineWidth(.6); c.line(35,y-9,560,y-9)
    return y-32

def note(s,y):
    rows=wrap(s,493,10.5)
    h=18*len(rows)+20
    c.setFillColor(LIGHT); c.setStrokeColor(LINE); c.roundRect(35,y-h+10,525,h,6,fill=1,stroke=1)
    p(s,y-8,x=51,width=493,size=10.5)
    return y-h-12

def image(name,x,y,w):
    file=ASSETS/name; im=Image.open(file); h=w*im.height/im.width
    c.drawImage(str(file),x,y,width=w,height=h,mask='auto'); return h

def table(rows,y,widths=(160,365)):
    for left,right in rows:
        lefts=wrap(left,widths[0]-20,11,True); rights=wrap(right,widths[1]-20,11)
        h=max(len(lefts),len(rights))*18+17
        c.setStrokeColor(LINE); c.setLineWidth(.5); c.line(35,y+7,560,y+7)
        for i,line in enumerate(lefts): t(43,y-12-i*18,line,11,True)
        for i,line in enumerate(rights): t(43+widths[0],y-12-i*18,line,11)
        y-=h
    c.line(35,y+7,560,y+7)
    return y-15

